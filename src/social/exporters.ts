// Hand-off to HyperFrames: single-file composition, Studio project zip,
// render variables, a text brief for HyperFrames' chat/MCP `compose`, and the
// builder's own JSON so a video can be reopened here later.

import JSZip from "jszip";
import { compileProject, compileStudioProject, totalDuration } from "./compile";
import { getComponent } from "./components";
import { getFormat } from "./formats";
import { getLayout } from "./layouts";
import type { SocialProject } from "./types";

const HF_VERSION = "0.8.81";

export function slugify(name: string): string {
  return name.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/(^-|-$)/g, "") || "social-video";
}

export function downloadBlob(filename: string, data: BlobPart, type: string): void {
  const url = URL.createObjectURL(new Blob([data], { type }));
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  a.click();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}

/** One self-contained index.html — the "Send to HyperFrames" import shape. */
export function downloadSingleHtml(project: SocialProject): void {
  downloadBlob(`${slugify(project.name)}.html`, compileProject(project, "export").html, "text/html");
}

export function variablesFile(project: SocialProject): Record<string, string | number | boolean> {
  return Object.fromEntries(compileProject(project, "export").variables.map((v) => [v.id, v.default]));
}

function readme(project: SocialProject): string {
  const format = getFormat(project.formatId);
  return `# ${project.name}

${format.name} · ${format.width}×${format.height} · ${totalDuration(project)}s · ${project.frames.length} frame(s)

Generated by the Atomic Social Media Builder as a HyperFrames project
(https://hyperframes.heygen.com). Each frame is a sub-composition in
\`compositions/\`, so it gets its own row in HyperFrames Studio.

## Preview, edit, render

\`\`\`bash
npx hyperframes@${HF_VERSION} preview        # open HyperFrames Studio
npx hyperframes@${HF_VERSION} check          # lint + layout + contrast gate
npx hyperframes@${HF_VERSION} render         # MP4 locally (needs FFmpeg)
npx hyperframes@${HF_VERSION} cloud render   # render on HeyGen's cloud
npx hyperframes@${HF_VERSION} publish        # private shareable link on hyperframes.dev
\`\`\`

## Editable variables

Brand colors are declared as variables on \`index.html\`; every text field is
a variable on its frame's sub-composition (see \`data-composition-variables\`),
editable in Studio. \`social-builder.json\` reopens this video in the builder.

## Safe zone

${format.safeZoneNote}
Safe area: top ${format.safeZone.top}px, right ${format.safeZone.right}px, bottom ${format.safeZone.bottom}px, left ${format.safeZone.left}px.
`;
}

/** Modular HyperFrames project, laid out like \`hyperframes init\` output. */
export async function downloadStudioZip(project: SocialProject): Promise<void> {
  const slug = slugify(project.name);
  const zip = new JSZip();
  const root = zip.folder(slug)!;
  for (const [path, body] of Object.entries(compileStudioProject(project))) root.file(path, body);
  root.file(
    "hyperframes.json",
    JSON.stringify(
      {
        $schema: "https://hyperframes.heygen.com/schema/hyperframes.json",
        registry: "https://raw.githubusercontent.com/heygen-com/hyperframes/main/registry",
        paths: { blocks: "compositions", components: "compositions/components", assets: "assets" },
        media: { autoProxy: true },
      },
      null,
      2,
    ),
  );
  root.file("meta.json", JSON.stringify({ id: slug, name: project.name, createdAt: new Date().toISOString() }, null, 2));
  root.file(
    "package.json",
    JSON.stringify(
      {
        name: slug,
        private: true,
        type: "module",
        scripts: {
          dev: `npx --yes hyperframes@${HF_VERSION} preview`,
          check: `npx --yes hyperframes@${HF_VERSION} check`,
          render: `npx --yes hyperframes@${HF_VERSION} render`,
          publish: `npx --yes hyperframes@${HF_VERSION} publish`,
        },
      },
      null,
      2,
    ),
  );
  root.file("README.md", readme(project));
  root.file("social-builder.json", JSON.stringify(project, null, 2));
  const blob = await zip.generateAsync({ type: "blob" });
  downloadBlob(`${slug}-hyperframes.zip`, blob, "application/zip");
}

/**
 * Plain-language brief for HyperFrames' hosted chat / MCP \`compose\` tool,
 * which builds a HeyGen-hosted project from a description rather than HTML.
 */
export function composeBrief(project: SocialProject): string {
  const format = getFormat(project.formatId);
  const sz = format.safeZone;
  const b = project.brand;
  const lines: string[] = [
    `Create a ${totalDuration(project)}-second ${format.name} video, ${format.width}x${format.height} (${format.aspect}), titled "${project.name}".`,
    project.enforceSafeZone
      ? `Keep all text, logos and CTAs inside the ${format.name} safe zone: ${sz.top}px from the top, ${sz.bottom}px from the bottom, ${sz.left}px left, ${sz.right}px right. Backgrounds may bleed full-frame.`
      : "",
    `Brand "${b.name}": primary ${b.colors.primary}, secondary ${b.colors.secondary}, accent ${b.colors.accent}, background ${b.colors.background}, text ${b.colors.text}. Use this copy verbatim — do not rewrite, add or drop claims.`,
    "",
  ];
  const describe = (layers: SocialProject["overlays"]) =>
    layers
      .filter((l) => l.enabled)
      .map((l) => {
        const def = getComponent(l.type);
        const copy = (def?.fields ?? [])
          .filter((f) => (f.type === "text" || f.type === "textarea") && l.props[f.key])
          .map((f) => `${f.label}: "${String(l.props[f.key]).replace(/\s+/g, " ").trim()}"`)
          .join("; ");
        const r = l.placement.rect;
        const pos = l.placement.ref === "frame" && r.w === 100 && r.h === 100 ? "full frame" : `${l.placement.ref === "safe" ? "safe area" : "frame"} x${r.x}% y${r.y}% w${r.w}% h${r.h}%`;
        return `  - ${def?.name ?? l.type} (${pos})${copy ? ` — ${copy}` : ""}`;
      })
      .join("\n");
  let t = 0;
  project.frames.forEach((f, i) => {
    lines.push(`Frame ${i + 1} "${f.name}" (${t}s–${t + f.duration}s, layout: ${getLayout(f.layoutId).name}):`);
    lines.push(describe(f.layers));
    t += f.duration;
  });
  if (project.overlays.some((l) => l.enabled)) {
    lines.push("Persistent across every frame:");
    lines.push(describe(project.overlays));
  }
  lines.push("", "Hard cuts between frames. Animate each element in (rise/fade/pop), keep subtle motion after the entrance, and scroll any ISI panel steadily so it stays legible.");
  return lines.filter((l, i, a) => !(l === "" && a[i - 1] === "")).join("\n");
}

export function downloadProjectJson(project: SocialProject): void {
  downloadBlob(`${slugify(project.name)}.social-builder.json`, JSON.stringify(project, null, 2), "application/json");
}

export async function readProjectJson(file: File): Promise<SocialProject> {
  const p = JSON.parse(await file.text()) as SocialProject;
  if (!Array.isArray(p.frames) || !p.brand?.colors || !p.formatId) throw new Error("That file isn't a Social Builder project.");
  return { ...p, overlays: p.overlays ?? [], updatedAt: Date.now() };
}
